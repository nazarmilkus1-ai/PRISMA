## Назначение

API/RPC — контрактный слой между компонентами PRISMA.

## Канонический подход

Вместо прямого доступа к чувствительным таблицам используются именованные gateway-функции.

Примеры:

- **get_public_market** — безопасное чтение публичного рынка;
- **participant_get_market** — рынок авторизованного участника;
- **participant_\*** — действия пользователя;
- **staff_\*** — административные функции;
- **bot_\*** — операции Telegram-бота.

## Категории

| Категория | Доступ |
|---|---|
| **PUBLIC** | Безопасные данные без авторизации |
| **PARTICIPANT** | Авторизованный участник |
| **STAFF** | Staff через RBAC |
| **BOT** | Серверный bot runtime |
| **PLUGIN** | Minecraft runtime |

## Безопасность RPC

Для каждого RPC определяются аргументы, результат, права, возвращаемые данные, ограничения и ошибки.

Наличие RPC в базе само по себе не означает, что его можно вызывать из браузера.

