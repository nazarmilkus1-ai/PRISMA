## Auth

**Auth user → users.auth_user_id → PRISMA user**

## Что хранится

Supabase содержит пользователей, заявки, наказания, репорты, апелляции, кланы, события, рынок, уведомления, рейтинги, статистику, Wiki и технические данные.

## RLS

Таблицы в exposed schema защищаются Row Level Security.

RLS дополняет серверные проверки и ограничивает строки, доступные конкретному пользователю.

## RPC

Используются явные gateway-функции:

- **PUBLIC** — безопасные данные;
- **PARTICIPANT** — авторизованный участник;
- **STAFF** — административные функции;
- **BOT** — Telegram runtime;
- **PLUGIN** — Minecraft runtime.

## Миграции

Production-схема изменяется через миграции, которые хранятся в репозитории.

