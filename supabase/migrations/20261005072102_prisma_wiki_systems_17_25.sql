## Основные уровни

**Auth → RBAC → RLS → серверные проверки → аудит**

Ни один интерфейсный элемент не является самостоятельной защитой.

## Данные

Публичный интерфейс не должен раскрывать Telegram ID, приватные Telegram username, service role keys, внутренние секреты или данные других пользователей без разрешения.

## RPC

Публичные функции должны возвращать только необходимые данные.

Критичные функции получают явный ACL и проверяют контекст пользователя.

## RLS

RLS используется на доменных таблицах exposed schema.

Ownership и роль проверяются на уровне базы там, где это требуется.

## Секреты

Секретные токены и ключи хранятся в runtime environment. Они не коммитятся в Git и не попадают в клиентский bundle.

## Логи

Логи и аудит не должны содержать секреты и лишние чувствительные данные.

## Изменения безопасности

После изменений Auth, RLS, RPC или ACL необходимо запускать проверки безопасности и регрессии.
