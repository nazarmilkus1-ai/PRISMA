| Подмена предмета | Кидает другой айтем в сундук | Проверяйте наведением (Shift) перед закрытием |
| Фейк-скрин оплаты | Присылает скрин «перевёл» | Не ведитесь — валюты нет, только предметы |
| Альт-аккаунты | Новый ник, 0 лвл, давит на сделку | /checkalt в боте (Staff), репорт |

