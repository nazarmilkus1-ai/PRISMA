### Цена — реалистичная
- Ориентируйтесь на недавние сделки в /market (сортировка по времени).
- Указывайте **конкретные предметы**, не «договоримся».
- Пример: 2 незеритовых блока + 32 эндер-перла (не «10к монет» — валюты нет!).

## Торг (Bargaining) — искусство сделки
### Как покупателю
1. Изучите рынок: 3–5 похожих объявлений.
2. Предложите **на 10–20% ниже** рыночной, но адекватно.
3. Комментарий: «Видел за X, готов взять за Y сейчас, тп к вам».
4. Макс 3 раунда — не затягивайте.

### Как продавцу
- Не принимайте первое низкое — давайте встречное (на 5–10% выше ихнего).
- Если предложение адекватно (разница < 5%) — принимайте, скорость = XP.
- Отклоняйте токсичных / неадекватных — блок в ЛС бота.

## Поиск выгодных сделок (Флиппинг)
- **BUY-объявления** часто выше рыночной — продавайте им.
- **Сезонные предметы** (снежки, тыквы, сердечки) — покупайте в сезон, продавайте после.
- **Ресурсы для крафта** (незерит, элитры, шалкеры) — стабильный спрос.
- **Услуги** (стройка ферм, помощь в битве) — высокие маржи, низкий риск.

## Анти-скм: защита от обмана
| Схема | Как распознать | Защита |
|---|---|---|
