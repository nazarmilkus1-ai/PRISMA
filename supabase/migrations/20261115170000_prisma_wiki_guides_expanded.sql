## Понимание системы
- **Elo** — ваша сила. Победа над сильнее = больше рейтинга.
- **K-фактор** падает с разницей рейтингов (см. Wiki: Рейтинговая система).
- **Сезон** = 8 недель. Топ-50 = уникальные награды.

## Выбор кита под стиль
| Стиль | Кит | Почему |
|---|---|---|
| Агрессивный, ближний | Воин | Щит + рывок = контроль дистанции |
| Дистанция, кайт | Лучник | Криты в прыжке, отстранённость |
| Бурст, комбо | Маг | Огненный шар + палка = взрывной урон |
| Выживание, каунтер | Танк | Стойка на малом HP, заставляет ошибаться |

**Совет:** Освойте 2 кита на выбор. Меняйте под оппонента.

## Фарм рейтинга: как и когда
### Оптимальное время
- **Вечер (19–23 МСК)** — максимум онлайна, разный скилл.
- **Выходные** — более слабые оппоненты (кажуалы).
- Избегайте утра — только хардкорные ратеры.

### Подбор оппонента
- Ищите рейтинг **±100** от вашего — макс. K-фактор (32).
- Избегайте «смертельных» мач-апов (например, Лучник vs Танк на близкой).
- Используйте /rating > смотрите недавние бои цели.

## Тактики за китами
### Воин vs Лучник
- Щит поднимайте **только** при выстреле (звук натягивания тетивы).
- Рывок > сразу удар, не давайте откайтиться.
- Блокируйте стрелки мечом (ПКМ) — 50% урона.

### Лучник vs Воин
- Держите 15+ блоков.
- Стреляйте в прыжке (крит 150%).
- При рывке воина — отстраивайтесь назад, стреляйте в ноги (замедление).

### Маг vs Все
- Огненный шар = зонирование. Загоняйте в угол.
- Комбо: Шар > сразу ПКМ палкой (огонь + прямой урон).
- Стойка танка — ждите окончания (20с), потом бурст.

### Танк vs Агресс
- Стойка на 40–50% HP — заставьте перерасходовать ресурсы.
- Контратака после стойки: меч + крит за спину.
- Не стойте на месте — танк медленный, используйте блоки для укрытий.

## Психология и дисциплина
- **Тилт** — главная причина потерь. Проигрыш 2 подряд > перерыв 10 мин.
- **Анализ демок** — записывайте бои (F2 + Replay Mod), разбирайте ошибки.
- **Рутина разогрева** — 2–3 битвы на нерейтинговом аккаунте / с другом.

