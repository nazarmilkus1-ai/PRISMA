**Результат:** Продление / Повышение / Понижение / Отстранение.

## Отгулы и неактивность
- Отгул > 7 дней > статус «Отгул» в панели (HEAD ADMIN ставит).
- Неактивность > 30 дней без отгула > авто-снятие роли.
- Возврат после перерыва > 60 дней > повторная стажировка (1 неделя).

## FAQ
**Q: Можно ли пропустить стажировку?**
A: Нет. Даже бывшие админы других проектов проходят (адаптация под PRISMA).

**Q: Что если ментор неадекватен?**
A: Жалоба HEAD ADMIN > смена ментора + проверка ментора.

**Q: Есть ли зарплата?**
A: Нет. PRISMA — некоммерческий, энтузиастский проект. Награды: XP, скины, префиксы, уважение.

