## Этапы карьеры
### 1. Helper (стажёр) — 2 недели стажировки
- **Наблюдение:** теневой режим с ментором (MOD+).
- **Теория:** прочтение Wiki STAFF раздела, тест по правилам.
- **Практика:** P3 репорты под контролем, автомод-логи.
- **Аттестация:** 3 кейса с ментором + тест (80%+).

### 2. Moderator — основная модерация
- Независимая обработка P1–P2 репортов.
- Команды: warn, mute (до 24ч), история, апелляции.
- Дежурства в автомоде, ревью фолз-позитивов.
- **Квартальная аттестация:** качество репортов, активность, отсутствие жалоб.

### 3. Operator — операции и ивенты
- Команды: kick, ban, события, кланы, настройки модулей.
- Ответственность за проведение ивентов, войны кланов.
- Менторство 1–2 Helper'ов.
- Доступ к расширенной аналитике в панели.

### 4. Admin — полное администрирование
- Управление персоналом (назначение/снятие ролей).
- Критические настройки (кроме инфраструктуры).
- Решение конфликтов Staff, эскалации игроков.
- Участие в стратегических решениях проекта.

### 5. Head Admin — лидерство
- Управление админами, матрица прав.
- Исключительные права (критические настройки, безопасность).
- Прямая связь с Owner.
- Ответственность за здоровье команды.

## Менторство (обязательно для Helper>Mod)
- Каждому Helper — ментор (Moderator+).
- Еженедельный 1-on-1 (15 мин): разбор ошибок, вопросы, план.
- Ментор отвечает за качество подопечного.
- Плохой ментор = ответственность ADMIN+.

## Квартальные аттестации (все Staff)
| Критерий | Вес |
|---|---|
