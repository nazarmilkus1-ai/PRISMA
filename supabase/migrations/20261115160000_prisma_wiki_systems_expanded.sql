## Формула Elo
Стандартная формула с K-фактором, зависящим от разницы рейтингов:
`
E_A = 1 / (1 + 10^((R_B - R_A) / 400))
R_A_new = R_A + K * (S_A - E_A)
`

| Разница рейтингов | K-фактор |
|---|---|
| < 100 | 32 |
| 100–200 | 24 |
| 200–400 | 16 |
| > 400 | 8 |

- S_A = 1 (победа), 0.5 (ничья), 0 (поражение).
- Минимальный рейтинг: 100 (не падает ниже).

## Сезоны
