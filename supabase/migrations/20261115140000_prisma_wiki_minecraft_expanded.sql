$# Minecraft FAQ

**Видосость:** PUBLIC

### ?? Игровой процесс
**Q: Как заработать XP и уровень?**
A: Играйте! XP даётся за: время в игре, убийства мобов/игроков, блоки, рыбалку, события, битвы, клановые активности.

**Q: Что за рейтинг и зачем он нужен?**
A: PvP-рейтинг (Elo). Растёт за победы в битвах и клановых войнах. Даёт доступ к топ-кланам, сезонным наградам, престижу.

**Q: Как создать клан?**
A: /clan create <тег> <название> — стоит 1000 XP. Минимум 3 участника для активности.

**Q: Как работает Player Battle?**
A: /battle <ник> — вызов на дуэль. Приняв, вы телепортируетесь на арену. Победитель получает рейтинг + XP.

### ?? Приваты и постройки
**Q: Как приватить территорию?**
A: Возьмите Golden Shovel (крафт: 2 золотых слитка + палка) > кликните по двум углам кубоида > /claim.

**Q: Можно ли приватить чужую постройку?**
A: Нет. Это груф. Наказание: warn + возврат > бан.

**Q: Пропал приват / чужой приват на моей постройке.**
A: Репорт в боте или /report в игре. Staff разберётся по логам.

### ?? Техническое
**Q: Сервер лагает / TPS низкий.**
A: Напишите в #support или боту. Админы проверят Spark профайлер.

**Q: Не могу зайти — \"Connection timed out\".**
A: Проверьте интернет, перезапустите лаунчер, попробуйте VPN. Если не помогло — репорт в боте.

**Q: Потерял предметы при смерти / баге.**
A: Только при баге сервера (дуп, краш) — репорт с доказательствами (демо, скрины). При обычной смерти — предметы не возвращаем.

### ?? Экономика и донат
**Q: Есть ли донат за реальные деньги?**
A: Нет. PRISMA — некоммерческий проект. Все функции доступны за игровую активность.

**Q: Как работает рынок?**
A: /market — объявления SELL/BUY/TRADE. Цены в тексте, сделка лично. Торг: /market bargain <id> <цена>.

**Q: Что за PRISMA Points (PP)?**
A: Внутренняя валюта за активность (в разработке). Будут для косметики, слотов домов, скинов.

### ?? Баги и читеры
**Q: Нашёл баг / эксплойт. Что делать?**
A: **Не используйте!** Репорт в боте (/report > «Баг») или в #staff-bugs. Награда за критический баг — до 5000 XP.

**Q: Вижу читера. Как пожаловаться?**
A: /report <ник> читы в игре или в боте. Обязательно: демка (F2 + запись), скрины. Без доказательств — только наблюдение.

