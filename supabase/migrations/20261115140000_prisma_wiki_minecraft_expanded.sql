## Bedrock Edition (1.20+)
1. Откройте Minecraft > Play > Servers > Add Server.
2. Имя: PRISMA.
3. Адрес: edrock.prisma.gg.
4. Порт: 19132.
5. Зайдите — авторизация через Geyser/Floodgate.

## PRISMA Auth (обязательно для Java)
PRISMA Auth связывает ваш Minecraft-ник с Telegram-аккаунтом.

### Как привязать:
1. Зайдите на сервер.
2. В чате появится код: Ваш код: ABC123.
3. Откройте Telegram-бота @PrismaBot.
4. Напишите /link ABC123 или нажмите кнопку «Привязать аккаунт».
5. Готово! Теперь вы участник PRISMA.

### Зачем это нужно:
- Доступ к участническим функциям (рейтинг, кланы, битвы, рынок).
- Синхронизация ника в Telegram и на сайте.
- Защита аккаунта от кражи.

## Частые проблемы
| Проблема | Решение |
|---|---|
| \"Connection refused\" | Проверьте адрес и порт. Java: 25565, Bedrock: 19132. |
| \"Invalid session\" | Перезапустите лаунчер, зайдите в Microsoft аккаунт. |
| \"Outdated server\" | Обновите игру до 1.20.4+. |
| Код PRISMA Auth не приходит | Проверьте чат сервера, попробуйте /code в игре. |
| \"You are not whitelisted\" | Сервер в режиме whitelist — подайте заявку через бота. |

