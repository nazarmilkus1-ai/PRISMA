- Фарм на альтах (XP, рейтинг, клановые очки) — сброс прогресса + бан.

## 6. Обжалование
- Апелляция через бота: /appeal или в личном кабинете на сайте.
- Срок рассмотрения: до 48 часов.
- Без доказательств (демки, скрины) бан не снимается.

