| AFK-фермы / автокликеры | warn > бан 1д |
| Лаг-машины /Entities краш | ban 1д > ban 7д |

## 4. Приваты и территории
- Приватите свои постройки (Golden Shovel / /claim).
- Не приватите чужие постройки без согласия.
- Не строьте рядом с чужими приватами без согласия (мин. 50 блоков).
