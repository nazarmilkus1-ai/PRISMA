$# Whitelist: как попасть на сервер PRISMA

**Видосость:** PUBLIC

## Когда нужен whitelist
- Сервер в техническом режиме (обновления, эксплойты).
- Новые сезоны (первые недели).
- По решению администрации.

## Как подать заявку
1. Зайдите в Telegram-бота @PrismaBot.
2. Нажмите «?? Подать заявку» или напишите /apply.
3. Заполните форму:
   - Имя и возраст (минимум 14 лет).
   - Minecraft-ник (Java / Bedrock).
   - Платформа.
   - Откуда узнали о PRISMA.
   - Цель на сервере (строить, PvP, кланы, контент).
4. Отправьте и ждите рассмотрения (обычно 1–24 часа).

## Требования к заявке
- Адекватное заполнение всех полей.
- Возраст 14+ (исключения — по решению ADMIN).
- Чистая история (нет банов на крупных проектах).
- Привязанный Telegram (для связи и уведомлений).

## После принятия
- Вас добавляют в whitelist.
- При заходе — проходите PRISMA Auth (см. гайд по подключению).
- Читаете правила (/rules).
- Можете начать играть!

## Частые причины отказа
- Возраст < 14 без согласования.
- Пустые/неадекватные поля «Цель» и «О себе».
- Найдены баны на других проектах за читы/грубые нарушения.
- Ник нарушает правила (оскорбления, реклама, нечитаемые символы).

## Апелляция отказа
- Напишите в поддержку через бота (/support).
- Объясните ситуацию, приведите аргументы.
- Решение — ADMIN+.

