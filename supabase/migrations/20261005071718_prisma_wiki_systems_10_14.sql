## Вход

1. Определить Telegram-пользователя.
2. Создать одноразовый код.
3. Передать код через Telegram.
4. Проверить код на сервере.
5. Создать или подтвердить Auth-сессию.
6. Связать Auth identity с профилем PRISMA.

## Связь с users

**Supabase Auth user → users.auth_user_id → профиль PRISMA**

Нельзя определять владельца данных только по Telegram ID или Minecraft-нику из клиентского запроса.

## Три уровня защиты

- **Authentication** — кто пользователь.
- **RBAC** — что ему разрешено.
- **RLS** — какие данные ему доступны.

## Безопасность

Нельзя доверять роли, переданной клиентом, обходить RLS через интерфейс или помещать секретные ключи в браузерный код.

Одноразовый код должен иметь ограниченный срок действия, быть одноразовым и становиться недействительным после использования.

## Административный доступ

**Auth → пользователь → роль → RBAC → разрешение действия**

Авторизация сама по себе не выдаёт административные права.

