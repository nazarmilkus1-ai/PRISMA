$md$# Маяк

Маяк излучает луч и даёт игрокам рядом полезные эффекты.

## Как сделать
- Звезда Нижнего мира, обсидиан и стекло.
- Звезду получают, победив **иссушителя**.

## Пирамида
- Под маяком строится пирамида из блоков железа, золота, изумрудов, алмазов или незерита.
- Чем больше уровней, тем больше эффектов и дальность.

## Эффекты
- Скорость, спешка, сопротивление, прыгучесть, сила, регенерация.
- Для активации нужен ресурс: слиток железа, золота, изумруд, алмаз или незерит.

## Условия
- Над маяком не должно быть непрозрачных блоков.
- Цвет луча меняется с помощью цветного стекла.

## Советы
- Ставьте маяк рядом с основной базой или фермой.
- Для долгой работы используйте скорость и спешку.
- Следите за ресурсами: их нужно вносить при смене эффектов.
- Следуйте правилам сервера по использованию больших построек.
- Укрепляйте окружение, чтобы мобы не ломали стекло.

## Дополнительно
Маяк — долгосрочный проект: для высоких уровней нужны большие запасы металла и алмазов. Планируйте пирамиду заранее и выбирайте место, где она не помешает другим постройкам. Договоритесь с сообществом о размещении общего маяка, чтобы все участники получали эффекты.
