$md$# Шалкер-бокс

Шалкер-бокс — компактный способ носить много предметов.

## Как получить
- Раковины шалкеров выпадают из **шалкеров** в городах Края.
- Из двух раковин и сундука делают бокс.
- Бокс можно красить.

## Особенности
- Содержимое сохраняется при переносе.
- Внутри шалкер-бокса нельзя хранить другой шалкер-бокс.
- Можно ставить на землю и открывать как сундук.

## Применение
- Транспортировка ценных предметов.
- Организация инвентаря: отдельные боксы для руды, блоков, зелий.
- Хранение вещей перед вылазками.

## Советы
- Подписывайте боксы разными цветами.
- Не оставляйте их без присмотра в опасных местах.
- Перед экспедицией разложите вещи по боксам заранее.
- Шалкеры стреляют снарядами, которые заставляют левитировать; берите защиту.
- Берегите ценные боксы: потеря даст сразу большой ущерб.

## Дополнительно
Шалкер-боксы стоят дорого по времени и ресурсам, поэтому относитесь к ним бережно. Для командных экспедиций заготовьте набор боксов со снаряжением. Не забывайте, что при перемещении в опасных местах можно потерять предмет, так что берегите его от лавы и огня.
