$md$# PRISMA Points (PP)

PP — внутренняя валюта сообщества. Баланс общий для Telegram, сайта и игры: баланс не может уйти в минус, а каждая операция записывается в историю.

## Как посмотреть
- В Telegram: команда `/pp` показывает баланс и последние операции.
- В игре: команда `/pp` или кнопка PRISMA Points в главном меню `/menu`.

## Как получить
- **Продать ресурсы серверу** в игровом меню (`/pp`, кнопка продажи): уголь, медные, железные и золотые слитки, лазурит, редстоун, изумруды и алмазы. Цены задаются за 16 штук, у каждого ресурса есть дневной лимит продажи.
- **Ивенты.** Победитель турнира получает призовой фонд (см. «Ивенты и взносы»).
- Награды за задания и достижения добавляются постепенно.
- Выдача от администрации: за конкурсы и особые случаи.

## Как потратить
- **Магазин в игре:** временные эффекты, например скорость, спешка, ночное зрение и регенерация. Покупка списывает PP сразу.
- **Взносы за ивенты.** Взнос списывается при записи.
- Косметика и улучшения будут добавляться в магазин.

## Переводы между игроками
`/pp send @ник 50` переводит 50 PP другому участнику. Можно от 1 до 100 000 PP за один перевод. Переводить могут только участники сообщества.

## Важно
- Баланс нельзя уменьшить ниже нуля: если PP не хватает, операция отклоняется.
- Повторный клик не списывает PP дважды: операции защищены от повторов.
- PP не имеют денежной стоимости и не обмениваются на реальные деньги.
- Подозрение на ошибку: напишите в поддержку (`/support`), история операций поможет разобраться.
