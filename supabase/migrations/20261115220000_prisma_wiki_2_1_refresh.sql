$md$# Ивенты и взносы в PP

Ивенты проходят на сервере по расписанию. Список: команда `/events` в боте или раздел «Ивенты» на сайте.

## Запись и взнос
- Запись открывается кнопкой в боте или на сайте. У ивента может быть взнос в PP, он указан в карточке («Взнос»).
- Взнос списывается при записи. Если PP не хватает, запись не оформляется, баланс смотрите командой `/pp`.
- **Отмена записи до старта возвращает взнос полностью.** После старта ивента или дедлайна регистрации отменить нельзя.

## Призовой фонд
- Фонд — это сумма всех оплаченных взносов.
- **10 % уходит проекту** (комиссия), **90 % получает победитель**. Остальные призёры PP не получают.
- Призы выплачивает администрация один раз после ивента.

## Какие ивенты готовятся
- **Чемпионат PvP.** Взнос 10 PP. Регистрация, случайные пары, сетка, до трёх дней на турнир, арена со зрителями.
- **Мафия.** Бесплатно, без приза. Игра на роли: мафия, шериф, мирные.
- **Судный день.** Взнос 10 PP. Раз в неделю в случайное время на сервере разрешены PvP и кражи; грифинг, лаг-машины и эксплойты запрещены.

Правила и даты каждого ивента публикуются в новостях заранее. Описания выше — план: ивент считается запущенным, только когда он появился в списке `/events`.
