## Главное меню
Команда `/menu` открывает меню PRISMA. Оно работает одинаково в Java и Bedrock: кнопки, а не ввод команд. Внутри:
- **PRISMA Points** — баланс, продажа ресурсов, магазин.
- Кланы, дома, точки появления, карта и прочие разделы, доступные вам по правам.

## Личная карта мира
`/worldmap` показывает только те места, где вы были, и ваши точки. Карта с «туманом»: неизведанное не видно.

## Могилы
После смерти предметы сохраняются в могиле. Список и безопасное получение предметов — команда `/grave`. Могила хранится ограниченное время (около 15 минут), поэтому не откладывайте. Последнее место смерти показывает `/lastdeath`.

## Дома и телепорты
- `/sethome`, `/home`, `/homes`, `/delhome` — личные дома.
- `/spawn` — телепорт на спавн.
- `/tpa <ник>`, `/tpaccept`, `/tpdeny` — запросы на телепортацию между игроками.
- `/coords` — показать или отправить координаты, `/checkpoint` — личные контрольные точки.

## Кланы
`/clan` — управление кланом, `/village` — село и территория клана.

## Вход и пароль (Java)
Java-игроки входят через PRISMA Auth: `/register`, `/login`, `/changepass`. Bedrock-игроки определяются через Floodgate и пароль не вводят.

## Мультиаккаунты
Несколько аккаунтов одного человека учитываются и связываются. Обход наказаний с помощью альтов приводит к наказанию всех аккаунтов.

Полный список команд: `/prismacommands`.
