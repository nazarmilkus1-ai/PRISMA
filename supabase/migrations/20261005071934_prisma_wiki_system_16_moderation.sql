# 16. Модерация

**Видимость:** MEMBER

## Назначение

Модерация PRISMA отвечает за поддержание правил сообщества, обработку нарушений и применение предусмотренных наказаний.

## Источники

Модерация работает с данными из Minecraft, Telegram, репортов, обращений поддержки и истории предыдущих наказаний.

## Основные действия

| Действие | Назначение |
|---|---|
| **WARN** | Предупреждение за нарушение. |
| **MUTE** | Ограничение общения. |
| **KICK** | Удаление игрока с сервера. |
| **BAN** | Ограничение доступа к серверу. |
| **UNWARN / UNMUTE / UNBAN** | Отмена соответствующего наказания при наличии права. |

## Принципы

1. Наказание должно иметь основание и причину.
2. Права проверяются через RBAC.
3. История наказаний сохраняется.
4. Участник может обжаловать наказание.
5. Репорт сам по себе не является доказательством вины.

## Синхронизация

Если наказание связано с Minecraft или Telegram, состояние должно синхронизироваться с PRISMA.

Изменение статуса наказания не должно оставлять старое состояние активным только в одной из систем.

## Апелляции

**Наказание → апелляция → проверка → решение → уведомление → аудит**

## Аудит

Критические действия Staff должны фиксироваться в истории.

## Безопасность

Модератор не должен получать права, которых нет у его роли. Интерфейс не является механизмом безопасности: доступ определяют серверная логика и RBAC.

## Связанные системы

Модерация связана с ролями, жалобами, апелляциями, уведомлениями, профилями, Telegram и Minecraft.
