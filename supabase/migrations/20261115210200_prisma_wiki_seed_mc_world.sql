$md$# Биомы Minecraft: обзор

Биом — область мира со своим климатом, растительностью, цветом травы и воды и набором мобов. Биом определяет, какие животные встретятся, будет ли идти снег или дождь и какие ресурсы лежат рядом.

## Как читать мир
- **Температура** решает, что падает с неба: дождь, снег или ничего (в пустыне дождя нет).
- **Растительность** подсказывает ресурсы: тёмный дуб и грибы, бамбук, акации, мангры.
- **Рельеф**: горы, равнины, реки, океаны и пещеры формируют маршруты и места для баз.

## Главные группы
- **Умеренные:** равнины, леса, берёзовые и тёмные леса, болота.
- **Холодные:** тайга, заснеженные равнины, горные луга и пики.
- **Тёплые:** пустыни, саванны, бесплодные земли (меза), джунгли.
- **Водные:** океаны, реки, пляжи, тёплые и холодные океаны.
- **Подземные:** лаш-пещеры, капельниковые пещеры, глубокая тьма.
- **Редкие:** грибные поля, вишнёвая роща, ледяные шипы.

