## 4. PRISMA Auth (привязка Minecraft)
После регистрации в боте:
1. Зайдите на сервер (play.prisma.gg).
2. В чате появится: Ваш код: ABC123.
3. В боте нажмите «?? Привязать Minecraft» или напишите /link ABC123.
