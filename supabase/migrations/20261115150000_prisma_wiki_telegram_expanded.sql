$# Автомодерация в Telegram

**Видосость:** PUBLIC

## Как это работает
Автомод — это набор правил, которые бот проверяет на каждом сообщении в группе.

### Проверяемые параметры
- **Запрещённые слова** (мат, оскорбления, сливы).
- **Ссылки** (только разрешённые домены: prisma.gg, youtube.com, twitch.tv).
- **Капс** (>70% заглавных в сообщении >10 символов).
- **Флуд** (>5 сообщений за 10 сек от одного юзера).
- **Упоминания** (@all, @here, массовые пинги).
- **Пересылаемые сообщения** из подозрительных чатов.
- **Стикеры/гифки** из запрещённых паков.

### Действия автомода
| Уровень | Действие |
|---|---|
| 1 | Удаление сообщения + предупреждение в ЛС |
| 2 | Мут 10 мин + уведомление Staff |
| 3 | Мут 1 ч + репорт в панель |
| 4 | Бан 1 д + эскалация ADMIN |

Настройки зависят от категории чата (общий / торговая / клановый / Staff).

## Настройка (только Staff)
Панель: /dashboard/moderation > вкладка «Автомод».
- Добавление/удаление слов в стоп-лист.
- Белые списки доменов и пользователей.
- Пороги капса/флуда.
- Исключения для ролей (VIP, Staff не мутятся).

## Фолз-позитивы (ошибки)
Иногда автомод срабатывает по ошибке:
- Технические термины, похожие на мат.
- Ссылки на GitHub, документацию.
- Цитаты из правил/вики.

### Что делать
1. Не спорьте с ботом в чате — это флуд.
2. Напишите в /support > «Автомод ошибся».
3. Пришлите скрин удалённого сообщения.
4. MODERATOR+ проверит лог и исправит правило.

## Логи автомода
- В группе: #staff-moderation-logs (только Staff).
- В панели: /dashboard/moderation > «Логи автомода».
- Хранятся 30 дней.

