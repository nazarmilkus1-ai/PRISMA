- Пещеры и шахты помечайте светом: он помогает ориентироваться и не пускает мобов позади.
- Ночью полезно ходить по освещённым дорогам. Подсветка тропы ощутимо снижает риск.

## Другие меры
- Двери, заборы и ограды останавливают многих мобов, но не всех: пауки лазают, зомби могут ломать двери на высокой сложности.
