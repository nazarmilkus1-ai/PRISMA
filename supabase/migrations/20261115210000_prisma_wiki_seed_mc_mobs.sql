$md$# Исчезновение мобов и лимит

Мир не хранит бесконечно много мобов: часть из них исчезает (деспавн), а общее число ограничено.

## Деспавн
- Враждебные мобы исчезают, когда вы далеко от них. Совсем далеко — почти сразу, на среднем расстоянии — с некоторым шансом.
- Мобы, которые держат предметы или подобрали экипировку, обычно сохраняются, пока их не убьют.
- Мирные животные деспавнятся редко, но не защищены от этого полностью.

## Как оставить моба
- **Бирка (name tag).** Моб с именем не исчезает. Бирки находят в сундуках, ловят рыбалкой, покупают у жителей.
- **Приручение и поводок.** Прирученные питомцы остаются. Поводок помогает увести животное.
- Загруженная область влияет на то, как ведут себя мобы: за пределами загруженных чанков мир «замирает».

## Лимит
У каждой категории мобов есть общий предел в загруженной области. Когда он достигнут, новые мобы не появляются. Поэтому большая ферма может забить лимит, а охота на мобов вокруг освободит место.

## Практические выводы
- Если рядом слишком много животных, новые не будут появляться. Это важно для ферм мобов.
- Не держите на базе лишних животных: они нагружают сервер.
- Игроки на общем сервере делят общий лимит окрестностей.
- Бирки полезны для ценных питомцев и лошадей.

## Советы
- Если моб пропал, возможно, он деспавнился. Бирка решает проблему навсегда.
- Для надёжного хранения животных используйте загоны и ограды.
