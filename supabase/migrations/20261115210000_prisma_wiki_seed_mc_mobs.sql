Враждебные мобы появляются там, где темно. Правильный свет — самый дешёвый способ сделать территорию безопасной.

## Чем освещать
- **Факелы.** Просты в изготовлении: уголь или древесный уголь и палка.
- **Фонари.** Красивее и ярче факелов.
- **Светокамень, морские фонари, лампы Редстоуна.** Хороши для оформления.
- **Лава и огонь.** Дают свет, но опасны.

## Как расставлять
- Освещайте не только пол, но и потолки, углы, подвалы, крыши и склоны вокруг дома.
