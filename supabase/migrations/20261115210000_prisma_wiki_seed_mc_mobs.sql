- **Расстояние.** Мобы появляются не слишком близко к игроку и не слишком далеко от него.
- **Сложность.** На «Мирной» враждебные мобы не появляются.

## Советы
- Освещайте территорию базы целиком, включая крыши, углы и подвалы.
- Полублоки и ступени могут оставлять тёмные участки, которые подходят для спавна.
