- Кошки отпугивают криперов и фантомов.
- Железные големы защищают деревни и поселения.

## Советы
- Проверяйте дом вечером: найдите тёмные места и осветите их.
- Не забывайте про подземные хранилища, фермы и туннели.
- Для ферм мобов, наоборот, нужна тёмная камера: там свет не нужен.
