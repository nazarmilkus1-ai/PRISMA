Спавнер — особый блок, который сам порождает мобов определённого типа. Внутри виден вращающийся образ существа.

## Где найти
- Зомби, скелеты и пауки — в подземельях (данжах).
- Пещерные пауки — в заброшенных шахтах.
- Блейзы — в крепостях Нижнего мира.
- Другие виды встречаются в особых постройках (например, в испытательных камерах).

## Как работает
Спавнер порождает мобов, если рядом есть игрок и достаточно места вокруг. Он использует собственный таймер и свою область. Свет частично мешает: у многих обычных спавнеров темнота нужна не всегда, но факелы подавляют некоторые виды.

## Для чего нужен
- **Ферма опыта и добычи.** Мобы стекают в удобное место, где их убивают.
- **Ресурсы.** Блейзы дают огненные стержни, скелеты — кости и стрелы, зомби — гнилую плоть.

## Безопасность
- Подойти к спавнеру неосторожно значит оказаться в окружении мобов.
- Закрывайте открытые стороны блоками или факелами, чтобы ограничить спавн.
- Обычно сам спавнер нельзя добыть в обычном режиме: его ломают, а блок не выпадает. Хотя кирка с шёлковым касанием не спасает: спавнер остаётся недоступным как предмет.

## Советы
- Берите оружие, блоки и еду.
- Ферму лучше строить рядом с проходом, чтобы мобы не расползались.
- Для Нижнего мира захватите огнестойкость.
- Не ломайте спавнер, если планируете ферму.
