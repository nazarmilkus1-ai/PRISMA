$md$# Мобы в Minecraft: обзор

Мобы — это живые существа игрового мира: животные, жители, монстры и боссы. От их поведения зависят безопасность базы, добыча ресурсов и ход всего выживания.

## Основные группы
- **Мирные.** Не нападают и не защищаются: корова, овца, свинья, курица, жители. Дают еду, шерсть, кожу и другие ресурсы.
- **Враждебные.** Атакуют игрока при встрече: зомби, скелет, крипер, ведьма, фантом и многие другие. Чаще всего появляются в темноте.
- **Нейтральные.** Не трогают игрока, пока их не разозлить: эндермен, волк, пчела, железный голем, зомбифицированный пиглин. Атаковать одного нейтрала иногда означает драку со всей группой.
- **Боссы.** Эндер-дракон, Иссушитель и Хранитель (по силе его часто приравнивают к боссам). Требуют серьёзной подготовки.

## Откуда берутся мобы
Большинство появляется само по правилам спавна (освещение, тип блока, биом, измерение). Мирных животных можно разводить, а часть мобов создаётся игроком: железный и снежный големы, Иссушитель.

## Зачем знать мобов
- Многие предметы можно получить только с мобов: порох, жемчуг Эндера, нити, огненные стержни, тотем бессмертия.
- Правильное освещение базы убирает большую часть угроз.
- Некоторые мобы дают возможность торговли и обмена (жители, пиглины, странствующий торговец).

## Советы
- Всегда носите с собой еду, оружие и блоки для укрытия.
- Узнавайте особенности нового моба до встречи: у каждого есть слабое место.
- Различия между Java и Bedrock есть в мелочах (поведение пауков, ИИ, шансы выпадения). Основные принципы одинаковы.
- Читайте отдельные статьи по каждому мобу в этой энциклопедии.
