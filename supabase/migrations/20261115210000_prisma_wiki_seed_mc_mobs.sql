- Появляются при генерации чанков на траве и подходящих блоках, главным образом на свету.
- Новые животные на уже исследованных местах обычно не возникают, поэтому ценных стоит разводить, а не ждать.

## Что влияет на спавн
- **Освещение.** Факелы, фонари и другие источники света блокируют появление врагов на освещённых блоках.
