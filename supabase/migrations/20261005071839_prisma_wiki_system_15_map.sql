# 15. Карта

**Видимость:** MEMBER

## Назначение

Карта PRISMA показывает мир Minecraft и доступные системе географические объекты: территории, деревни, события и другие разрешённые точки.

## Что используется

Текущая система использует данные PRISMA и встроенное отображение карты на сайте.

**Dynmap не является обязательной частью PRISMA.**

## Публичная карта

Публичная карта может показывать только данные, предназначенные для общего просмотра:

- разрешённые маркеры;
- активные деревни;
- публичные события и точки;
- географические объекты без приватной информации.

## Кабинет участника

Авторизованный участник получает доступ к дополнительным возможностям карты согласно RBAC и доступности модуля.

## Кланы и территории

Клановые территории и деревни являются частью игровой модели PRISMA. Их данные должны поступать из единого источника данных.

## Безопасность

Данные, которые не предназначены для публичного просмотра, не должны попадать в public RPC или клиентский JSON.

Модерационные и административные действия с картой выполняются только через разрешённые RPC.

## Источник истины

**Supabase → RPC → сайт / панель / Minecraft**

Сайт не является отдельным источником данных карты.

## Связанные системы

Карта связана с Minecraft-интеграцией, кланами, деревнями, событиями, историей и RBAC.
