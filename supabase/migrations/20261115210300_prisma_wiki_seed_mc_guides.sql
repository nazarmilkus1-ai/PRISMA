## Повторитель
Повторитель принимает сигнал сзади и отдаёт его вперёд с полной силой 15. Правой кнопкой по нему задают задержку от 1 до 4 тиков редстоуна (один тик редстоуна — 0,1 секунды).

Что он умеет:
- **усиливать** затухающий сигнал;
- **задерживать** сигнал для настройки порядка срабатывания;
- **пропускать сигнал в одну сторону**, не давая ему вернуться;
- **«запираться»**: если сбоку подать на него сигнал от другого повторителя или компаратора, он фиксирует своё состояние. На этом строятся схемы памяти.

## Компаратор
У компаратора есть два режима. Переключаются правым щелчком (передний факелок горит или нет).

**Режим сравнения.** Сигнал сзади проходит вперёд, только если он не слабее боковых сигналов.

**Режим вычитания.** Из заднего сигнала вычитается наибольший из боковых.

## Считывание контейнеров
Если компаратор стоит за сундуком, бочкой, воронкой, печью, варочной стойкой и подобными блоками, он выдаёт сигнал, пропорциональный заполненности. Это основа сортировщиков, счётчиков и датчиков «переполнения».

Также компаратор читает состояние некоторых блоков: например, торт, книжная полка с книгами (чиселённая), кафедра, улей. Не все варианты одинаково работают в обеих версиях, проверяйте на тесте.

## Типичные ошибки
- Забыли направление: стрелка повторителя показывает, куда идёт сигнал.
- Компаратор поставлен не в том режиме.
