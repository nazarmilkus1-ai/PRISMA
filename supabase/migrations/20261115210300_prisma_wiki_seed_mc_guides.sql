## Проверьте адрес и порт
- Адрес и порт должны совпадать с тем, что дала администрация.
- Порт указывается отдельным полем. Для Bedrock используется протокол UDP.
- Лишние пробелы и опечатки в адресе — частая причина.

## Версия игры
- Если клиент слишком старый или слишком новый, сервер откажет. Сообщение может говорить об «устаревшем клиенте» или «устаревшем сервере».
- Обновите игру до последней стабильной версии. Если сервер ещё не поддерживает новую версию, подождите объявления.

## Сеть
- Попробуйте другой интернет (Wi-Fi или мобильная сеть).
- Отключите VPN.
- Перезапустите роутер.
- Проверьте, не блокирует ли сеть UDP (бывает в школах и офисах).

## Учётная запись
- Войдите в аккаунт Microsoft/Xbox.
- Для консолей может требоваться подписка на онлайн-сервис (зависит от платформы).
- Проверьте возрастные настройки и разрешения мультиплеера.

