## RS-защёлка (NOR-латч)
Два NOR-элемента замыкаются друг на друга. У схемы два входа:
- **S (set)** — включить;
- **R (reset)** — выключить.

После короткого импульса на S выход остаётся включённым, пока не придёт импульс на R. Одновременно подавать оба сигнала не нужно: результат неопределён.

## Защёлка на повторителях
Повторитель можно запереть боковым сигналом. Ставят два повторителя, которые держат друг друга в замкнутом состоянии. Это компактная версия на плоскости.

## Т-триггер (переключатель одной кнопкой)
Один импульс включает, следующий выключает. Схему часто делают на липком поршне, который двигает блок редстоуна, или на дроппере с компаратором. Это основа «кнопки-лампы».

## Для чего использовать
- свет по одной кнопке;
- запоминающий замок: нужная комбинация, затем открытие двери;
- «режим тревоги» после срабатывания датчика, пока его не сбросят;
- управление несколькими фермами сразу.

## Советы
- Всегда делайте вручную проверку: включить, выключить, одновременно подать сигналы.
- Подписывайте входы S и R табличками.
- Для сброса при перезапуске учтите, что состояние может зависеть от загрузки чанков.
