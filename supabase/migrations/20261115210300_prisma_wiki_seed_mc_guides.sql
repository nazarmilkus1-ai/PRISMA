**Geyser** — программа, которая переводит протокол Bedrock в протокол Java. Благодаря ей игроки Bedrock (телефоны, консоли, Windows) заходят на Java-сервер и играют вместе с игроками Java.

## Что такое Floodgate
**Floodgate** позволяет заходить игрокам Bedrock **без аккаунта Java**. Они входят через учётную запись Microsoft/Xbox, а сервер принимает их как игроков.

## Что это значит для вас
- На сервере действуют правила **Java-версии**: бой, редстоун, мобы и фермы.
- Игроки Bedrock и Java видят друг друга и общаются в чате.
- У игроков Bedrock может быть специальный префикс в имени (это настройка сервера).

## Подключение с Bedrock
1. Откройте «Играть», затем «Серверы», затем «Добавить сервер».
2. Введите адрес и порт, которые сообщила администрация.
3. Сохраните и подключитесь.

Порт по умолчанию у Bedrock — 19132 (UDP), но сервер может использовать другой.

## Консоли
На консолях в меню нельзя добавить свой сервер по адресу напрямую, нужно обходное решение. Спросите у администрации, поддерживается ли это.

## Особенности
- Часть Java-механик на Bedrock отображается иначе.
- Некоторые элементы интерфейса (меню, сундуки) показываются как стандартные окна.
- Версия клиента должна подходить для сервера; при обновлениях возможны задержки.

