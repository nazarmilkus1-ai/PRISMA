## Правила Java
Вы играете на Java-сервере, а значит:
- **Бой:** действует перезарядка удара. Быстрые клики не дают преимущества. Бейте в такт.
- **Редстоун:** схемы для Java работают так, как задумано. Чертежи для Bedrock могут вести себя иначе.
- **Команды:** синтаксис Java (например, `/effect give`, а не `/effect @s`).
- **Фермы:** выбирайте чертежи для Java.

## Интерфейс
- Меню и окна сервера (магазины, меню) могут выглядеть как сундуки с предметами. Нажимайте по слотам как обычно.
- Подсказки по командам иногда неполные: ориентируйтесь на Wiki.
- Если пишете в чате, учитывайте, что на телефоне клавиатура закрывает обзор.

## Управление
- Настройте чувствительность.
- На сенсорном экране включайте крупные кнопки.
- Для точных ударов геймпад или клавиатура удобнее сенсорного экрана.

## Предметы и мир
- Предметы и блоки в целом совпадают, но отдельные модели могут выглядеть иначе.
- Пользовательские ресурсы сервера могут отображаться по-другому.
- Часть звуков и частиц может отличаться.

## Учётная запись
Вход идёт через аккаунт Microsoft/Xbox. Ваш прогресс сохраняется на сервере под вашим именем.

