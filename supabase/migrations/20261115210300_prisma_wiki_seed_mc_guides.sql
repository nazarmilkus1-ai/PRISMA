## Редстоуновая пыль
Пыль переносит сигнал. У сигнала есть **сила от 0 до 15**. С каждым блоком пыли сила падает на единицу, поэтому провод длиннее 15 блоков затухает. Продлить его можно **повторителем**.

## Как сигнал попадает в механизм
- Пыль соединяется с соседней пылью и с потребителями, к которым ведёт.
- Непрозрачный блок, на который подан сигнал, сам становится источником для соседей. Это называют «питанием через блок».
- Стекло и некоторые другие блоки сигнал не пропускают.

## Потребители
Поршни, лампы, двери, люки, раздатчики, дропперы, воронки, нотные блоки и многое другое.

