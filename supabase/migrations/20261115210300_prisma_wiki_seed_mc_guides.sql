Часы выдают повторяющийся сигнал: включён, выключен, снова включён. Нужны для автоматических ферм, дозаторов и мигающих ламп.

## Простые схемы
- **Повторители в кольце.** Цепочка повторителей, замкнутая в петлю с одним импульсом. Скорость задаётся задержкой.
- **Часы на воронках.** Две воронки передают друг другу предмет, компаратор снимает сигнал. Скорость зависит от числа предметов.
- **Часы на наблюдателях.** Два наблюдателя, смотрящих друг на друга, дают очень быстрый цикл. Это самые быстрые и самые тяжёлые для сервера часы.
- **Часы на факеле.** Факел, питающий сам себя через блок. Работают быстро, но легко «выгорают».

## Управление часами
Включайте их рычагом или тем же датчиком, что и ферму. Лучше, когда ферма работает только пока вы рядом или пока нужна.

## Нагрузка на сервер
Быстрые часы каждый тик обновляют блоки вокруг. На общем сервере это снижает TPS и вредит всем игрокам. Рекомендации:
1. Не оставляйте бесконечные быстрые часы работать постоянно.
2. Предпочитайте медленные таймеры и воронки.
3. Не строите большое число одинаковых схем рядом.
4. Если схема стала причиной лагов, администрация вправе её отключить или убрать.

## Ловушка «выгорания»
Если факел слишком часто переключается, он временно перестаёт работать. Для надёжных схем используйте повторители и наблюдатели.
