$md$# Логические элементы

Логические элементы — «кирпичики» сложных схем. У каждого есть входы (A, B) и выход.

## NOT (инвертор)
Редстоуновый факел на блоке. Если блок запитан, факел гаснет. Входной сигнал есть — выхода нет, и наоборот.

## OR («или»)
Два провода сходятся в один. Выход включён, если включён **хотя бы один** вход. Это самый простой элемент.

## NOR
OR с инвертором на выходе. Включён только когда оба входа выключены.

## AND («и»)
Выход включён, только если включены **оба** входа. Классическая схема: каждый вход инвертируется факелом, результаты соединяются в OR и снова инвертируются. По закону де Моргана это то же самое, что A и B.

## XOR
Включён, если входы **различаются**. Применяется в схемах переключателей и счётчиков.

## Зачем это нужно
- кодовый замок: комбинация рычагов и AND;
- «две кнопки с разных сторон открывают одну дверь»: OR;
- защёлки и память: NOR-пара создаёт RS-триггер;
- сигнализации, которые срабатывают только при совпадении условий.

## Советы
- Повторитель на выходе делает сигнал чистым и полной силы.
- Выносите тестовые рычаги на видное место и проверяйте все четыре комбинации входов.
- Факел «выгорает» при слишком частых переключениях: не используйте очень быстрые часы на факелах.
