$md$# Редстоун: Java и Bedrock

Основные блоки редстоуна есть в обеих версиях, но поведение отличается. Схема, которая работает в Java, может не работать в Bedrock, и наоборот.

## Главные различия
- **Квази-связность.** В Java поршни, раздатчики и дропперы реагируют на сигнал, поданный по диагонали выше блока. В Bedrock этой особенности нет. Многие компактные дверные схемы Java на ней и построены.
- **Порядок обновления.** В Java порядок срабатывания соседних блоков определён и повторяется. В Bedrock он может быть иным, поэтому одновременное срабатывание нескольких поршней менее предсказуемо.
- **Мелкие отличия.** Задержки и поведение некоторых блоков (наблюдатели, поршни, слизь и мёд) различаются.
- **Скорость часов.** Быстрые схемы ведут себя неодинаково.

## Что это значит на практике
1. Ищите чертёж именно под вашу версию. В названии роликов часто пишут «Java» или «Bedrock».
2. Проверяйте схему на тестовом участке перед большой постройкой.
3. Простые схемы (рычаг, лампа, повторитель, поршневая дверь на обычной подаче сигнала) обычно переносятся без проблем.

## Если вы играете через Geyser
Сервер на Java-движке обрабатывает редстоун по правилам Java, даже если вы заходите с Bedrock. Значит, **схемы для Java** будут работать так, как задумано, а вот для Bedrock-чертежей возможны сюрпризы. Подробнее см. статью про Geyser.

## Совет
Если схема «почему-то не включается», проверьте направление повторителей, питание сбоку и наличие квази-связности в чертеже.
