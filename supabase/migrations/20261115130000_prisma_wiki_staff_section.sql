## Расширение полномочий
1. **Инициатива** — Staff пишет заявку в #staff-internal с обоснованием.
2. **Ревью** — непосредственный руководитель проверяет компетенции.
3. **Голосование** — ADMIN+ голосуют в панели (модуль *Admins*).
4. **Назначение** — HEAD ADMIN или OWNER подтверждает через RPC staff_manage_admin.

