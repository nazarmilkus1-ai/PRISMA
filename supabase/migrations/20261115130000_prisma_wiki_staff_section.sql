## Общие
**Q: Можно ли играть на основном аккаунте, будучи Staff?**
A: Да, но не используй Staff-права в своих интересах (телепортация к себе, выдача предметов, проверка своих репортов).

**Q: Что делать, если друг нарушил правила?**
A: Эскалируй другому модератору. Не рассматривай репорты на друзей/кланмейтов/партнёров.

**Q: Как сообщить об отгуле?**
A: Напиши в #staff-schedule или HEAD ADMIN в ЛС. Ставим статус «Отгул» в панели Admins.

## Модерация
**Q: Игрок оскорбил в ЛС бота. Это нарушение?**
A: Только если это спам/флуд/угрозы. Обычные оскорбления в ЛС — не модерация (игрок может заблокировать бота).

**Q: Читер признался, но доказательств нет. Бан?**
A: Без доказательств (демка, логи античита, скрины) — только warn + наблюдение. Бан требует доказательной базы.

**Q: Игрок просит разбан за донат/услуги. Что делать?**
A: Никаких сделок. Бан снимается только через апелляцию или если ошибкаStaff. Репорт в #staff-corruption если игрок давит.

## Панель и бот
**Q: Не заходит в админку — «Access Denied».**
A: Проверь: 1) MFA включён (AAL2), 2) есть запись в dmins таблице, 3) роль не истекла. Обратись к ADMIN+.

**Q: Бот не реагирует на команды.**
A: Проверь /admin/api/health > если 500, рестарт на Render. Если 200 — проверь webhook в настройках бота.

**Q: Как добавить новость в Telegram-канал?**
A: В панели /dashboard/news создай NEWS с галочкой «Опубликовать» > бот сам запостит в канал (если настроен webhook).

