## Назначение
Staff (персонал) — это команда, обеспечивающая стабильную работу экосистемы PRISMA: Minecraft-сервер, Telegram-бот, сайт и админ-панель. Staff не «главные» на сервере, а **служба поддержки и модерации**.

## Основные принципы
- **Минимально необходимые права** — доступ даётся только под задачи.
- **Прозрачность** — все критические действия фиксируются в аудите.
- **Коллективные решения** — баны, разбаны, изменение ролей обсуждаются.
- **Соблюдение иерархии** — эскалация идёт снизу вверх.

## Структура Staff
| Роль | Описание |
|---|---|
| **HELPER** | Первичная поддержка, ответы на типовые вопросы, модерация чата. |
| **MODERATOR** | Работа с репортами, наказаниями, апелляциями. |
| **OPERATOR** | Расширенные операционные права: события, кланы, настройки модулей. |
| **ADMIN** | Полный административный доступ в рамках делегированных полномочий. |
| **HEAD ADMIN** | Управление админами, стратегические решения, исключительные права. |
| **OWNER** | Конечное принятие решений, инфраструктура, юридические вопросы. |

## Зоны ответственности
- **Модерация Minecraft** — чат, читы, баги, нарушения правил.
- **Модерация Telegram** — автомод, спам, конфликты, апелляции.
- **Техподдержка** — помощь игрокам, разбор багов, навигация по Wiki.
- **События** — проведение ивентов, награды, турнирные таблицы.
- **Инфраструктура** — деплои, мониторинг, бэкапы, безопасность.
- **Обучение** — менторство новичков, проведение стажировок.

