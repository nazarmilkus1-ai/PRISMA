## Репорты (Reports)
**Статусы:** OPEN > IN_REVIEW > RESOLVED / DISMISSED

### Процесс
1. **Поступление** — игрок создаёт репорт через бота или сайт.
2. **Триаж** — MODERATOR оценивает приоритет (P1–P3).
   - P1: читы, угрозы, баги безопасности — реакция < 1 ч.
   - P2: нарушения чата, гриф — реакция < 6 ч.
   - P3: споры, вопросы — реакция < 24 ч.
3. **Разбор** — сбор логов, скринов, допросы сторон.
4. **Решение** — наказание / отклонение / передача выше.
5. **Закрытие** — игрок получает уведомление с причиной.

### Инструменты панели
- /dashboard/reports — список с фильтрами.
- /dashboard/reports/[id] — детали: логи чата, история наказаний, привязки.
- Горячие клавиши: R — взять в работу, Enter — открыть.

## Апелляции (Appeals)
**Статусы:** OPEN > IN_REVIEW > APPROVED / REJECTED

### Правила
- Рассматривает **другой** модератор (не выдавший наказание).
- Срок рассмотрения: до 48 ч.
- Игрок может приложить доказательства (демки, скрины).
- Решение: снятие/сокращение наказания или оставление.

## Поддержка (Support Tickets)
**Статусы:** OPEN > IN_REVIEW > RESOLVED > CLOSED

### Категории
- Техподдержка (баги сайта, бота, игры).
- Вопросы по правилам/вики.
- Жалобы на Staff (попадают к ADMIN+).
- Партнёрство/медиа.

### SLA
- Первичный ответ: < 4 ч (рабочее время).
- Решение: < 24 ч для P2, < 72 ч для P3.

