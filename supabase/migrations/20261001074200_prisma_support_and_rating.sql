-- PRISMA support and product rating.
-- The live database was migrated with this same DDL through Supabase MCP.
create table if not exists public.prisma_ratings (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users(id) on delete cascade,
  value integer not null check (value between 1 and 5),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id)
);
create index if not exists prisma_ratings_created_at_idx on public.prisma_ratings(created_at);

create table if not exists public.support_requests (
  id uuid primary key default gen_random_uuid(),
  ticket_no bigint generated by default as identity unique,
  user_id uuid references public.users(id) on delete set null,
  telegram_id bigint not null,
  message text not null check (char_length(trim(message)) between 3 and 4000),
  status text not null default 'OPEN' check (status in ('OPEN','IN_REVIEW','RESOLVED','CLOSED')),
  admin_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);
create index if not exists support_requests_status_created_idx on public.support_requests(status,created_at desc);
create index if not exists support_requests_telegram_created_idx on public.support_requests(telegram_id,created_at desc);

alter table public.prisma_ratings enable row level security;
alter table public.support_requests enable row level security;
revoke all on table public.prisma_ratings from anon, authenticated;
revoke all on table public.support_requests from anon, authenticated;

create or replace function public.bot_rate_prisma(p_tg_id bigint,p_value integer)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_user_id uuid; v_avg numeric; v_count integer;
begin
 if p_value < 1 or p_value > 5 then return jsonb_build_object('success',false,'error','INVALID_VALUE'); end if;
 select id into v_user_id from public.users where telegram_id=p_tg_id and deleted_at is null and status='ACCEPTED'::public.application_status limit 1;
 if v_user_id is null then return jsonb_build_object('success',false,'error','NOT_APPROVED'); end if;
 insert into public.prisma_ratings(user_id,value) values(v_user_id,p_value)
 on conflict(user_id) do update set value=excluded.value,updated_at=now();
 select round(avg(value)::numeric,2),count(*) into v_avg,v_count from public.prisma_ratings;
 return jsonb_build_object('success',true,'value',p_value,'average',v_avg,'count',v_count);
end;
$$;

create or replace function public.bot_get_prisma_rating(p_tg_id bigint default null)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_user_id uuid; v_my integer; v_avg numeric; v_count integer;
begin
 if p_tg_id is not null then
   select id into v_user_id from public.users where telegram_id=p_tg_id and deleted_at is null limit 1;
   if v_user_id is not null then select value into v_my from public.prisma_ratings where user_id=v_user_id; end if;
 end if;
 select round(avg(value)::numeric,2),count(*) into v_avg,v_count from public.prisma_ratings;
 return jsonb_build_object('success',true,'average',coalesce(v_avg,0),'count',v_count,'my_value',v_my);
end;
$$;

create or replace function public.bot_create_support_request(p_tg_id bigint,p_message text)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_user_id uuid; v_limit integer; v_used integer; v_ticket bigint;
begin
 if p_tg_id is null or p_message is null or char_length(trim(p_message)) not between 3 and 4000 then
   return jsonb_build_object('success',false,'error','INVALID_MESSAGE');
 end if;
 select id into v_user_id from public.users where telegram_id=p_tg_id and deleted_at is null limit 1;
 v_limit := case when v_user_id is null then 1 else 2 end;
 select count(*) into v_used from public.support_requests where telegram_id=p_tg_id and created_at >= date_trunc('day',now());
 if v_used >= v_limit then return jsonb_build_object('success',false,'error','DAILY_LIMIT','limit',v_limit,'used',v_used); end if;
 insert into public.support_requests(user_id,telegram_id,message) values(v_user_id,p_tg_id,trim(p_message)) returning ticket_no into v_ticket;
 return jsonb_build_object('success',true,'ticket_no',v_ticket,'remaining',greatest(v_limit-v_used-1,0),'limit',v_limit);
end;
$$;

create or replace function public.bot_list_support_requests(p_admin_tg_id bigint,p_status text default 'OPEN',p_limit integer default 30)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_admin uuid; v_rows jsonb;
begin
 select id into v_admin from public.users where telegram_id=p_admin_tg_id and deleted_at is null limit 1;
 if v_admin is null or not private.prisma_has_user_permission(v_admin,'support.manage') then return jsonb_build_object('success',false,'error','PERMISSION_DENIED'); end if;
 select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc),'[]'::jsonb) into v_rows
 from (select s.id,s.ticket_no,s.telegram_id,s.message,s.status,s.admin_note,s.created_at,s.updated_at,u.minecraft_nickname,u.telegram_username
       from public.support_requests s left join public.users u on u.id=s.user_id
       where (p_status is null or p_status='' or s.status=p_status)
       order by s.created_at desc limit greatest(1,least(p_limit,100))) x;
 return jsonb_build_object('success',true,'items',v_rows);
end;
$$;

create or replace function public.bot_manage_support_request(p_admin_tg_id bigint,p_ticket_no bigint,p_status text,p_note text default null)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_admin uuid; v_status text := upper(trim(p_status)); v_id uuid;
begin
 select id into v_admin from public.users where telegram_id=p_admin_tg_id and deleted_at is null limit 1;
 if v_admin is null or not private.prisma_has_user_permission(v_admin,'support.manage') then return jsonb_build_object('success',false,'error','PERMISSION_DENIED'); end if;
 if v_status not in ('OPEN','IN_REVIEW','RESOLVED','CLOSED') then return jsonb_build_object('success',false,'error','INVALID_STATUS'); end if;
 update public.support_requests set status=v_status,admin_note=case when p_note is null then admin_note else trim(p_note) end,
 resolved_at=case when v_status in ('RESOLVED','CLOSED') then coalesce(resolved_at,now()) else null end,updated_at=now()
 where ticket_no=p_ticket_no returning id into v_id;
 if v_id is null then return jsonb_build_object('success',false,'error','TICKET_NOT_FOUND'); end if;
 return jsonb_build_object('success',true,'ticket_no',p_ticket_no,'status',v_status);
end;
$$;

revoke all on function public.bot_rate_prisma(bigint,integer) from public,anon,authenticated;
